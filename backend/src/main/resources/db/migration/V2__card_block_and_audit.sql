-- Source of truth for block state. Redis only caches it.
CREATE TABLE card_block (
    card_ref   VARCHAR(64)  PRIMARY KEY,
    blocked    BOOLEAN      NOT NULL,
    reason     VARCHAR(500),
    updated_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Append-only: the code only ever INSERTs and SELECTs here.
CREATE TABLE audit_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    actor        VARCHAR(100) NOT NULL,
    action       VARCHAR(16)  NOT NULL,
    card_ref     VARCHAR(64)  NOT NULL,
    alert_id     UUID,
    reason       VARCHAR(500),
    before_state VARCHAR(16)  NOT NULL,
    after_state  VARCHAR(16)  NOT NULL
);

CREATE INDEX idx_audit_card_occurred ON audit_event (card_ref, occurred_at, id);